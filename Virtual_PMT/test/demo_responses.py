def get_demo_response(phase: str, agent_type: str, query: str) -> str:
    """
    Get a pre-generated demo response instantly.
    
    Args:
        phase: Product phase (ideation, research, design, etc.)
        agent_type: Type of agent
        query: User's query (we'll match keywords)
    
    Returns:
        Pre-generated response string
    """
    query_lower = query.lower()
    
    # Try to match query to a template
    if phase in DEMO_RESPONSES and agent_type in DEMO_RESPONSES[phase]:
        responses = DEMO_RESPONSES[phase][agent_type]
        
        # Match keywords
        for keyword, response in responses.items():
            if keyword in query_lower:
                return response
        
        # If no match, return first response
        return list(responses.values())[0]
    
    # Fallback generic response
    return f"""# {agent_type.replace('_', ' ').title()} Analysis

Based on your request: "{query}"

This is a demo mode response. In production, this would be generated by the LLM based on your specific requirements.

## Key Points
- Analysis specific to {phase} phase
- Tailored recommendations
- Data-driven insights
- Actionable next steps

[Note: Enable full LLM mode for custom responses]
"""


def is_demo_mode_available(phase: str, agent_type: str, query: str) -> bool:
    """
    Check if a demo response is available for this query.
    
    Returns:
        True if we have a cached response, False if need LLM
    """
    query_lower = query.lower()
    
    if phase not in DEMO_RESPONSES:
        return False
    if agent_type not in DEMO_RESPONSES[phase]:
        return False
    
    responses = DEMO_RESPONSES[phase][agent_type]
    for keyword in responses.keys():
        if keyword in query_lower:
            return True
    
    return False